"""
Cross-model comparison of FlexTern workload profiles (EXP-0002B).

Reads the generated outputs of ternary_model_profile.py for several models
and writes results/workload_profile/cross_model/comparison.md and
comparison.json: architecture table, dot lengths with divisibility, ternary
distribution, sparsity structure, output head, accumulator widths, and a
union of all observed K values with the widths a Y-Architecture would need
to cover them.

It does not compute anything new from weights; it only joins and formats
what the per-model profiles already measured. Classification of properties
as generalizing / model-specific / uncertain is done in the experiment
record, not here.

Usage (from repo root, after profiling each model):
    python analysis/cross_model_compare.py
"""

from __future__ import annotations

import csv
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from model_specs import ACT_FORMAT_MAX, ACT_FORMAT_MIN, ACT_MODEL_MAX, ACT_MODEL_MIN, SPECS  # noqa: E402
from ternary_model_profile import accumulator_width, divisibility  # noqa: E402

MODELS = ["bitnet-2b4t", "falcon-e-1b", "falcon-e-3b"]


def load(slug: str) -> dict:
    d = SPECS[slug].default_out
    with open(os.path.join(d, "model_summary.json"), encoding="utf-8") as f:
        ms = json.load(f)
    def rows(name):
        with open(os.path.join(d, name), encoding="utf-8") as f:
            return list(csv.DictReader(f))
    xc = None
    p = os.path.join(d, "ternarization_crosscheck.json")
    if os.path.exists(p):
        with open(p, encoding="utf-8") as f:
            xc = json.load(f)
    return {"slug": slug, "summary": ms, "by_module": rows("weight_distribution_by_module.csv"),
            "dots": rows("dot_length_summary.csv"), "acc": rows("accumulator_widths.csv"),
            "mem": rows("memory_representation.csv"), "traffic": rows("decode_traffic_model.csv"),
            "crosscheck": xc}


def main() -> int:
    out_dir = os.path.join("results", "workload_profile", "cross_model")
    os.makedirs(out_dir, exist_ok=True)
    M = [load(s) for s in MODELS]
    names = [m["summary"]["model_id"].split("/")[-1] for m in M]
    L = []
    A = L.append
    A("# Cross-model comparison — generated by analysis/cross_model_compare.py (do not hand-edit)")
    A("")
    A("Sources: each model's `model_summary.json` and CSVs under `results/workload_profile/`. All MEASURED unless marked. See EXP-0002B for interpretation.")
    A("")

    # ---- 1. Architecture ----
    A("## 1. Architecture (config.json, MEASURED)")
    A("")
    A("| Property | " + " | ".join(names) + " |")
    A("|---|" + "---|" * len(M))
    def row(label, fn):
        A(f"| {label} | " + " | ".join(str(fn(m)) for m in M) + " |")
    s = lambda m: m["summary"]
    row("family", lambda m: s(m)["family"])
    row("revision", lambda m: s(m)["revision"][:12])
    row("license", lambda m: s(m)["license"].split(";")[0].split(" (")[0])
    row("architecture class", lambda m: s(m)["architectures"][0] + " / " + s(m)["model_type"])
    row("total parameters", lambda m: f"{s(m)['parameters']['total']:,}")
    row("ternary parameters", lambda m: f"{s(m)['parameters']['ternary_linear']:,} ({s(m)['parameters']['pct_ternary']:.1f}%)")
    row("layers", lambda m: s(m)["num_hidden_layers"])
    row("hidden size", lambda m: s(m)["hidden_size"])
    row("intermediate size", lambda m: s(m)["intermediate_size"])
    row("intermediate / hidden", lambda m: f"{s(m)['intermediate_size'] / s(m)['hidden_size']:.2f}")
    row("attention heads", lambda m: s(m)["num_attention_heads"])
    row("KV heads (GQA ratio)", lambda m: f"{s(m)['num_key_value_heads']} ({s(m)['gqa_group_size']}:1)")
    row("head dim", lambda m: s(m)["head_dim"])
    row("context length", lambda m: f"{s(m)['max_position_embeddings']:,}")
    row("vocabulary", lambda m: f"{s(m)['vocab_size']:,}")
    row("MLP activation", lambda m: s(m)["hidden_act"])
    row("norms per layer", lambda m: f"{s(m)['norms_per_layer']} ({', '.join(n.split('.')[-1] for n in s(m)['norm_names'])})")
    row("tied embeddings", lambda m: s(m)["tie_word_embeddings"])
    row("attention", lambda m: s(m)["attention"])
    row("scale convention (checkpoint)", lambda m: s(m)["scale_convention"] + (" (stored = β)" if s(m)["scale_convention"] == "multiply" else " (stored = 1/β)"))
    row("weight_scale range", lambda m: f"{s(m)['global_ternary_distribution']['weight_scale_min']:.4f}–{s(m)['global_ternary_distribution']['weight_scale_max']:.4f}")
    row("checkpoint file bytes", lambda m: f"{s(m)['file_size_bytes']:,}")
    row("SHA-256 verified", lambda m: s(m)["file_sha256_matches_hf_etag"])
    A("")

    # ---- 2. Projection shapes ----
    A("## 2. Ternary projection shapes per layer (N × K, MEASURED)")
    A("")
    A("| Module | " + " | ".join(names) + " |")
    A("|---|" + "---|" * len(M))
    for mod in ("q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj", "down_proj"):
        cells = []
        for m in M:
            r = next(x for x in m["by_module"] if x["module"] == mod)
            cells.append(f"{r['N']} × {r['K']} ({float(r['pct_of_ternary']):.1f}%)")
        A(f"| {mod} | " + " | ".join(cells) + " |")
    A("")

    # ---- 3. Dot lengths and divisibility ----
    A("## 3. Dot-product lengths K (MEASURED) and divisibility")
    A("")
    A("| Model | K | Modules | % of ternary weights | % zero | E[nonzero] | ÷64 | ÷128 | ÷256 | ÷512 |")
    A("|---|---:|---|---:|---:|---:|---|---|---|---|")
    all_k = {}
    for m, nm in zip(M, names):
        for r in m["dots"]:
            k = int(r["K"])
            all_k.setdefault(k, set()).add(nm)
            A(f"| {nm} | {k} | {r['modules']} | {float(r['pct_of_ternary_weights']):.1f}% | {float(r['pct_zero']):.2f}% | {float(r['expected_nonzero_terms']):,.0f} | "
              + " | ".join("yes" if r[f"div_{d}"] == "True" else "no" for d in (64, 128, 256, 512)) + " |")
    A("")
    A("Union of observed K values across models:")
    A("")
    A("| K | Models | ÷64 | ÷128 | ÷256 | ÷512 | largest power of 2 dividing K |")
    A("|---:|---|---|---|---|---|---:|")
    for k in sorted(all_k):
        dv = divisibility(k)
        p2 = k & -k
        A(f"| {k} | {', '.join(sorted(all_k[k]))} | " + " | ".join("yes" if dv[f"div_{d}"] else "no" for d in (64, 128, 256, 512)) + f" | {p2} |")
    gcd = 0
    import math
    for k in all_k:
        gcd = math.gcd(gcd, k)
    A("")
    A(f"GCD of all observed K: {gcd}. Largest power of two dividing every observed K: {gcd & -gcd}. (MEASURED arithmetic on {len(all_k)} values from {len(M)} checkpoints; not a statement about models not inspected.)")
    A("")

    # ---- 4. Ternary distribution ----
    A("## 4. Ternary value distribution (MEASURED)")
    A("")
    A("| Property | " + " | ".join(names) + " |")
    A("|---|" + "---|" * len(M))
    g = lambda m: s(m)["global_ternary_distribution"]
    row("ternary weights", lambda m: f"{g(m)['total_ternary_weights']:,}")
    row("% -1", lambda m: f"{g(m)['pct_neg']:.3f}%")
    row("% 0", lambda m: f"{g(m)['pct_zero']:.3f}%")
    row("% +1", lambda m: f"{g(m)['pct_pos']:.3f}%")
    row("|%+1 − %-1|", lambda m: f"{abs(g(m)['pct_pos'] - g(m)['pct_neg']):.3f} pts")
    row("per-tensor zero rate min / median / max", lambda m: f"{g(m)['tensor_zero_rate_min_pct']:.1f} / {g(m)['tensor_zero_rate_median_pct']:.1f} / {g(m)['tensor_zero_rate_max_pct']:.1f}%")
    row("per-tensor zero rate std", lambda m: f"{g(m)['tensor_zero_rate_std_pct']:.2f} pts")
    row("reserved code 3 count", lambda m: g(m)["reserved_code3_count"])
    A("")
    A("Zero rate by module (%):")
    A("")
    A("| Module | " + " | ".join(names) + " |")
    A("|---|" + "---|" * len(M))
    for mod in ("q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj", "down_proj"):
        A(f"| {mod} | " + " | ".join(f"{float(next(x for x in m['by_module'] if x['module'] == mod)['pct_zero']):.2f}" for m in M) + " |")
    A("")

    # ---- 5. Sparsity structure ----
    A("## 5. Sparsity structure (MEASURED)")
    A("")
    A("| Property | " + " | ".join(names) + " |")
    A("|---|" + "---|" * len(M))
    d = lambda m: s(m)["dead_channels"]
    row("all-zero rows (all tensors)", lambda m: f"{d(m)['total_allzero_rows_all_tensors']:,}")
    row("all-zero columns (all tensors)", lambda m: f"{d(m)['total_allzero_cols_all_tensors']:,}")
    row("dead MLP intermediate channels", lambda m: f"{d(m)['mlp_intermediate_channels_dead_total']:,} of {d(m)['mlp_intermediate_channels_total']:,} ({d(m)['pct_mlp_intermediate_channels_dead']:.2f}%)")
    row("% ternary weights in dead rows", lambda m: f"{d(m)['pct_ternary_weights_in_dead_rows']:.2f}%")
    A("")
    A("See each model's `workload_summary.md` for the aligned-group (g = 4/8/16) table. In all three checkpoints the g-group all-zero rate matches the independence prediction p^g once all-zero rows are excluded, except for rows with individually extreme zero rates (q/k) which inflate g=16 without forming blocks.")
    A("")

    # ---- 6. Output head ----
    A("## 6. Output head and non-ternary weights (MEASURED)")
    A("")
    A("| Property | " + " | ".join(names) + " |")
    A("|---|" + "---|" * len(M))
    h = lambda m: s(m)["head"]
    row("head tensor", lambda m: h(m)["tensor"])
    row("head dtype", lambda m: h(m)["dtype"])
    row("tied to embedding", lambda m: h(m)["tied"])
    row("head params", lambda m: f"{h(m)['params']:,}")
    row("head bytes", lambda m: f"{h(m)['bytes'] / 1e6:,.1f} MB")
    row("head % of file bytes", lambda m: f"{h(m)['pct_of_file_bytes']:.1f}%")
    row("head % of linear MACs/token", lambda m: f"{s(m)['operation_summary']['pct_linear_macs_lm_head_bf16']:.1f}%")
    row("ternary layer bytes (2-bit)", lambda m: f"{int(float(next(x for x in m['mem'] if x['representation'].startswith('ACTUAL checkpoint packed'))['bytes'])) / 1e6:,.1f} MB")
    row("head % of stream-once weight bytes/token (INFERRED)", lambda m: f"{float(m['traffic'][0]['pct_head']):.0f}%")
    row("KV read/token @4096 (INFERRED)", lambda m: f"{float(m['traffic'][0]['kv_cache_read_bytes_per_token_at_context']) / 1e6:,.1f} MB")
    row("KV read/token @max ctx (INFERRED)", lambda m: f"{float(m['traffic'][0]['kv_cache_read_bytes_per_token_at_max_context']) / 1e6:,.1f} MB @ {s(m)['max_position_embeddings']:,}")
    A("")

    # ---- 7. Accumulators ----
    A("## 7. Accumulator widths for every observed K (INFERRED mathematically)")
    A("")
    A("| K | Models | Format [-128,127] sum max | Format bits | Model [-127,127] sum max | Model bits | Max nonzero/row observed | Data-bounded bits |")
    A("|---:|---|---:|---:|---:|---:|---:|---:|")
    acc_json = []
    for k in sorted(all_k):
        f = accumulator_width(k, ACT_FORMAT_MIN, ACT_FORMAT_MAX); a = accumulator_width(k, ACT_MODEL_MIN, ACT_MODEL_MAX)
        mx = max(int(r["max_nonzero_in_any_row"]) for m in M for r in m["acc"] if int(r["K"]) == k and r["max_nonzero_in_any_row"])
        db = accumulator_width(mx, ACT_MODEL_MIN, ACT_MODEL_MAX)
        acc_json.append({"K": k, "models": sorted(all_k[k]), "format_bits": f["signed_bits"], "model_bits": a["signed_bits"],
                         "max_nonzero_row": mx, "data_bounded_bits": db["signed_bits"]})
        A(f"| {k} | {', '.join(sorted(all_k[k]))} | {f['sum_max']:,} | {f['signed_bits']} | {a['sum_max']:,} | {a['signed_bits']} | {mx:,} | {db['signed_bits']} |")
    A("")
    A("Tile sizes (not model K): 256 → 17 (format) / 16 (model) bits; 512 → 18 / 17; 1024 → 19 / 18.")
    A("")

    # ---- 8. Quantization scheme ----
    A("## 8. Quantization scheme (KNOWN from reference code; scale convention confirmed on latents)")
    A("")
    A("| Property | " + " | ".join(names) + " |")
    A("|---|" + "---|" * len(M))
    row("weights", lambda m: s(m)["weight_quantization"])
    row("activations", lambda m: s(m)["activation_quantization"])
    row("code source", lambda m: s(m)["code_source"])
    def xc(m):
        c = m["crosscheck"]
        if not c:
            return "not run"
        return "; ".join(f"{t['tensor'].replace('model.layers.', 'L')}: f32 {t.get('agreement_pct_float32_math', t.get('agreement_pct', 0)):.2f}%"
                         + (f", bf16-emu {t['agreement_pct_bf16_emulated']:.2f}%" if 'agreement_pct_bf16_emulated' in t else "")
                         + f", scale {'ok' if t.get('scale_convention_confirmed_to_bf16_precision', t.get('scale_matches_absmean_to_bf16_precision')) else 'MISMATCH'}"
                         for t in c["tensors"])
    row("latent cross-check", xc)
    A("")

    with open(os.path.join(out_dir, "comparison.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    with open(os.path.join(out_dir, "comparison.json"), "w", encoding="utf-8") as f:
        json.dump({"models": {m["slug"]: {"model_id": s(m)["model_id"], "revision": s(m)["revision"],
                                           "K": [int(r["K"]) for r in m["dots"]],
                                           "pct_zero": g(m)["pct_zero"], "pct_neg": g(m)["pct_neg"], "pct_pos": g(m)["pct_pos"],
                                           "dead_mlp_channels_pct": d(m)["pct_mlp_intermediate_channels_dead"],
                                           "head": h(m), "scale_convention": s(m)["scale_convention"]} for m in M},
                   "all_K": sorted(all_k), "gcd_K": gcd, "largest_pow2_dividing_all_K": gcd & -gcd,
                   "accumulators": acc_json}, f, indent=2)
    print(f"wrote {out_dir}/comparison.md and comparison.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
