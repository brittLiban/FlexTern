"""Aggregate Stage A run outputs into results/edge_inference/summary.md (+ summary.json).

Reads only committed per-run artifacts (summary.json / manifest.json); nothing is recomputed
here, so every number in the report is traceable to a run directory.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from .common import RESULTS

RUNS = RESULTS / "runs"


def _load(p: Path):
    return json.loads(p.read_text()) if p.exists() else None


def collect() -> list[dict]:
    rows = []
    for summ in sorted(RUNS.glob("*/*/*/summary.json")):
        d = summ.parent
        man = _load(d / "manifest.json") or {}
        rows.append({"clip": d.parents[1].name, "runtime": d.parent.name, "run": d.name, "mode": man.get("mode"),
                     "role": man.get("role"), "summary": _load(summ), "manifest": man})
    return rows


def power_label(man: dict) -> str:
    """AC/battery state at run start. Runs before the host_state fix stored the raw code glued to the plan name."""
    h = man.get("host", {})
    if h.get("battery_status_code") is not None:
        return "AC" if h["battery_status_code"] in (2, 3, 6, 7, 8, 9, 11) else "battery"
    tail = (h.get("power_plan") or "")[-1:]
    return {"2": "AC*", "1": "battery*"}.get(tail, "unknown")  # * = recovered from the raw string of the first-version parser


def f(x, n=3):
    return "n/a" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{n}f}"


def build() -> tuple[str, dict]:
    rows = collect()
    out = ["# EXP-0010 Stage A — generated results summary", "",
           "Generated by `python -m analysis.edge_inference.report` from the committed per-run `summary.json` files. "
           "All numbers are **MEASURED** on the host described in each run's manifest; none is an energy measurement.", ""]
    cal = _load(RESULTS / "calibration.json")
    if cal:
        out += [f"Operating threshold (selected on the calibration clip only, B0 offline): **tau = {cal['tau']:.2f}**", ""]
    par = _load(RESULTS / "parity.json")
    if par:
        out += ["## Parity (development clip, every 4th frame of the first 2000)", "",
                f"- head tensors torch vs ORT: max |Δcls_logits| = {par['head_max_abs_diff_cls_logits_torch_vs_ort']:.2e}, max |Δbbox| = {par['head_max_abs_diff_bbox_regression_torch_vs_ort']:.2e}",
                f"- AP50: official `model(img)` {par['ap50']['official']['ap50']:.4f}, shared-pipeline B0 {par['ap50']['shared_B0']['ap50']:.4f}, B1 {par['ap50']['shared_B1']['ap50']:.4f}",
                f"- frames with identical detection count at score>=0.3: official vs B0 {par['compare_official_vs_shared_B0_score_ge_0.3']['frames_same_detection_count']}/{par['compare_official_vs_shared_B0_score_ge_0.3']['frames']}, B0 vs B1 {par['compare_shared_B0_vs_B1_score_ge_0.3']['frames_same_detection_count']}/{par['compare_shared_B0_vs_B1_score_ge_0.3']['frames']}",
                f"- tolerance checks: {par['pass']}", ""]
    al = _load(RESULTS / "alignment_sweep.json")
    if al:
        out += ["## Ground-truth/video alignment sweep (development clip, B0 detections vs GT shifted by k frames)", "",
                "| shift k | " + " | ".join(str(k) for k in al["ap50_by_gt_frame_shift"]) + " |", "|---|" + "---|" * len(al["ap50_by_gt_frame_shift"]),
                "| AP50 | " + " | ".join(f(v, 4) for v in al["ap50_by_gt_frame_shift"].values()) + " |", "",
                f"argmax shift = {al['argmax_shift']} (aligned: {al['aligned']})", ""]

    off = [r for r in rows if r["mode"] == "offline"]
    if off:
        out += ["## Offline quality (every frame, no pacing)", "",
                "| clip | runtime | rep | AP50 (floor) | AP50 (no floor) | P | R | F1 | R small/med/large | AP50 95% CI | F1 95% CI | fps | dets sha256[:12] |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for r in off:
            s = r["summary"]
            bs = s.get("bootstrap") or {}
            out.append(f"| {r['clip']} | {r['runtime']} | {r['run']} | {f(s['ap50'])} | {f(s['ap50_no_size_floor'])} | {f(s['precision'])} | {f(s['recall'])} | {f(s['f1'])} | "
                       f"{f(s.get('recall_small'),2)}/{f(s.get('recall_medium'),2)}/{f(s.get('recall_large'),2)} | "
                       f"{('[%s, %s]' % (f(bs['ap50_ci95'][0]), f(bs['ap50_ci95'][1]))) if bs else 'n/a'} | {('[%s, %s]' % (f(bs['f1_ci95'][0]), f(bs['f1_ci95'][1]))) if bs else 'n/a'} | "
                       f"{f(s['offline_throughput_fps'],1)} | {s['detections_sha256'][:12]} |")
        out.append("")
        # determinism between repeats
        by = {}
        for r in off:
            by.setdefault((r["clip"], r["runtime"]), []).append(r["summary"]["detections_sha256"])
        out += ["Determinism (identical detections across offline repeats): " + "; ".join(f"{k[0]}/{k[1]}: {'IDENTICAL' if len(set(v)) == 1 else 'DIFFERENT'} (n={len(v)})" for k, v in by.items() if len(v) > 1), ""]

    rep = [r for r in rows if r["mode"] == "replay"]
    if rep:
        out += ["## Real-time replay (source frame rate)", "",
                "| clip | runtime | run | power | processed | dropped | p50 | p95 | p99 | max (ms) | > deadline | decode / pre / infer / post mean (ms) | feeder slip p99 (ms) | peak RSS (MB) | avg busy cores | AP50 incl. drops | F1 incl. drops |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for r in rep:
            s = r["summary"]
            L, st = s["latency_ms"], s["stage_ms"]
            q = s["quality_including_drops"]
            out.append(f"| {r['clip']} | {r['runtime']} | {r['run']} | {power_label(r['manifest'])} | {s['processed']} | {s['dropped']} | {f(L['p50'],1)} | {f(L['p95'],1)} | {f(L['p99'],1)} | {f(L['max'],1)} | {s['deadline_missed_processed']} | "
                       f"{f(st['decode_ms']['mean'],1)} / {f(st['pre_ms']['mean'],1)} / {f(st['infer_ms']['mean'],1)} / {f(st['post_ms']['mean'],1)} | {f(s['feeder_slip_ms_p99'],2)} | "
                       f"{f(s['resources']['rss_peak_mb'],0)} | {f(s['resources']['avg_busy_cores'],2)} | {f(q['ap50'])} | {f(q['f1'])} |")
        out.append("")
        grp = {}
        for r in rep:
            if r["run"].startswith("replay_r") and not r["manifest"].get("max_frames"):  # short runs are not repeats of the full clip
                grp.setdefault((r["clip"], r["runtime"], power_label(r["manifest"])), []).append(r["summary"]["latency_ms"])
        out += ["### Repeat-to-repeat variability of latency percentiles (same clip, same runtime, fresh process each; `*` = power state recovered from the raw string recorded by the first-version host-state parser)", "",
                "| clip | runtime | power | n | p50 range (ms) | p95 range (ms) | p99 range (ms) |", "|---|---|---|---|---|---|---|"]
        for (c, rt, pw), v in grp.items():
            if len(v) > 1:
                rg = lambda k: f"{min(x[k] for x in v):.1f}–{max(x[k] for x in v):.1f}"  # noqa: E731
                out.append(f"| {c} | {rt} | {pw} | {len(v)} | {rg('p50')} | {rg('p95')} | {rg('p99')} |")
        out.append("")
    data = {"calibration": cal, "parity": par, "alignment": al,
            "runs": [{k: r[k] for k in ("clip", "runtime", "run", "mode", "summary")} for r in rows]}
    return "\n".join(out) + "\n", data


def main():
    md, data = build()
    (RESULTS / "summary.md").write_text(md, encoding="utf8")
    (RESULTS / "summary.json").write_text(json.dumps(data, indent=1, sort_keys=True, default=float), encoding="utf8")
    print(md.encode("ascii", "replace").decode())


if __name__ == "__main__":
    main()
