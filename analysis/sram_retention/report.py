ROOT = os.path.abspath(os.path.join(_HERE, "..", ".."))
OUT = os.path.join(ROOT, "results", "sram_retention")


def write_csv(name: str, rows: list[dict]) -> None:
    if not rows:
        return
    keys = []
    for r in rows:
        for k in r:
            if k not in keys:
                keys.append(k)
    with open(os.path.join(OUT, name), "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=keys); w.writeheader(); w.writerows(rows)


def copy_spice(out: str) -> None:
    src = os.path.join(_HERE, "spice")
    for name in ("asap7_cell_leakage.csv", "hold_snm.csv"):
        p = os.path.join(src, name)
        if os.path.exists(p):
            with open(p, encoding="utf-8") as f, open(os.path.join(out, name), "w", encoding="utf-8") as g:
                g.write(f.read())


def main() -> None:
    os.makedirs(OUT, exist_ok=True)
    ws = LS.load_workloads()
    scheds = {(slug, bits): LS.schedule(w, bits) for slug, w in ws.items() for bits in (2.0, 4.5)}
    R.write(OUT)
    copy_spice(OUT)
    write_csv("layer_schedule.csv", LS.schedule_rows(ws))
    write_csv("leakage_temperature.csv", RT.leakage_temperature_rows())
    write_csv("retention_voltage.csv", RT.retention_voltage_rows())
    write_csv("wake_latency_energy.csv", WK.wake_rows(scheds))
    write_csv("wake_slack_sweep.csv", C.wake_sweep_rows(scheds))
    write_csv("voltage_domain_sweep.csv", C.voltage_domain_rows(scheds))
    write_csv("retention_policy_sweep.csv", C.policy_rows(scheds))
    write_csv("token_rate_sweep.csv", C.token_rate_rows(scheds))
    write_csv("duty_cycle_sweep.csv", C.duty_rows(scheds))
    write_csv("session_sweep.csv", C.session_rows(scheds))
    write_csv("temperature_sweep.csv", C.temperature_rows(scheds))
    write_csv("int4_comparison.csv", C.int4_rows(scheds))
    write_csv("mode_sensitivity.csv", C.mode_sensitivity_rows(scheds))
    write_csv("break_even.csv", C.break_even_rows(scheds))
    write_csv("system_reconnect.csv", C.system_rows(scheds, ws))
    write_csv("exp0008_reconnect.csv", C.exp0008_reproduction_rows(scheds))
    prim = C.primary_rows(scheds); write_csv("primary_comparison.csv", prim)
    walk = C.walkthrough_rows(scheds); write_csv("falcon_e_1b_walkthrough.csv", walk)
    try:
        commit = subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, text=True).strip()
    except Exception:
        commit = "unknown"
    env = {"commit": commit, "date": str(date.today()), "python": platform.python_version(), "platform": platform.platform(),
           "spice": "ngspice 45.2 (Debian, WSL) + OpenVAF 23.5.0 compiled BSIM-CMG 110 (dwarning/VA-Models vacode110) + ASAP7 r1p7 models; decks in analysis/sram_retention/spice/",
           "inputs": "results/workload_profile/*/weight_distribution_by_layer.csv; EXP-0008 evidence.py constants"}
    with open(os.path.join(OUT, "environment.json"), "w", encoding="utf-8") as f:
        json.dump(env, f, indent=2)
    summary(commit, scheds, prim, walk)
    print("sram_retention results written")


