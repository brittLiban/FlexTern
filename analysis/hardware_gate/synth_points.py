"""
EXP-0005 generic synthesis sweep: generates one Yosys script per parameter point
(synth/exp0005/<name>.ys, committed), runs them, and parses the logs into
results/hardware_gate/synthesis.csv.

Methodology is the repository's EXP-0001 flow: read -sv, hierarchy with -chparam,
proc, flatten, opt_clean, stat (coarse cells: were multipliers inferred?), then
`synth -top <m> -flatten` with default ABC, stat (generic gate-level cells), plus
`ltp -noff` (longest topological path through generic gates, flip-flops excluded:
a technology-independent logic depth, NOT a frequency).

Memories are not part of any synthesized module (weight memories and activation
buffers are ports); flip-flop counts are therefore the only state and are
checked against the analytical register budget (no N x K state).

Tools:  --tool yowasp  (Yosys 0.69 WebAssembly, canonical in this repo)
        --tool wsl     (native Yosys in WSL Ubuntu; faster for the large points)
Logs go to results/hardware_gate/synth/<name>.txt.
"""

from __future__ import annotations

import argparse
import csv
import json
import os
import re
import subprocess
import sys
import time

_HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(_HERE, "..", ".."))
SYNTH_DIR = os.path.join("synth", "exp0005")
LOG_DIR = os.path.join("results", "hardware_gate", "synth")

RTL_TERNARY = ["rtl/y_core.sv", "rtl/ternary_unpack4.sv", "rtl/sum_tree.sv", "rtl/y_stream_engine.sv"]
RTL_BANK = RTL_TERNARY + ["rtl/y_memory_bank.sv"]
RTL_TOP = RTL_BANK + ["rtl/y_near_memory_engine.sv"]
RTL_INT4 = ["rtl/sum_tree.sv", "rtl/int4_stream_baseline.sv"]

# name, top, sources, params, terms/cycle, bytes/cycle, kind
POINTS = [
    ("unpack4",            "ternary_unpack4",       ["rtl/ternary_unpack4.sv"], {}, 4, 1, "decode"),
    ("stream_b16_r1",      "y_stream_engine",       RTL_TERNARY, {"BYTES": 16,  "ROWQ": 1}, 64,   16,  "stream"),
    ("stream_b64_r1",      "y_stream_engine",       RTL_TERNARY, {"BYTES": 64,  "ROWQ": 1}, 256,  64,  "stream"),
    ("stream_b128_r1",     "y_stream_engine",       RTL_TERNARY, {"BYTES": 128, "ROWQ": 1}, 512,  128, "stream"),
    ("stream_b256_r1",     "y_stream_engine",       RTL_TERNARY, {"BYTES": 256, "ROWQ": 1}, 1024, 256, "stream"),
    ("stream_b16_r4",      "y_stream_engine",       RTL_TERNARY, {"BYTES": 16,  "ROWQ": 4}, 256,  64,  "stream-multirow"),
    ("stream_b1_r64",      "y_stream_engine",       RTL_TERNARY, {"BYTES": 1,   "ROWQ": 64}, 256, 64,  "stream-output-parallel"),
    ("bank_b16",           "y_memory_bank",         RTL_BANK, {"BYTES": 16}, 64,  16, "bank"),
    ("bank_b32",           "y_memory_bank",         RTL_BANK, {"BYTES": 32}, 128, 32, "bank"),
    ("bank_b64",           "y_memory_bank",         RTL_BANK, {"BYTES": 64}, 256, 64, "bank"),
    ("nearmem_nb4_b16",    "y_near_memory_engine",  RTL_TOP, {"NB": 4, "BYTES": 16}, 256, 64, "near-memory-top"),
    ("nearmem_nb4_b64",    "y_near_memory_engine",  RTL_TOP, {"NB": 4, "BYTES": 64}, 1024, 256, "near-memory-top"),
    ("int4_b128",          "int4_stream_baseline",  RTL_INT4, {"BYTES": 128}, 256, 128, "int4-baseline"),
    ("int4_b64",           "int4_stream_baseline",  RTL_INT4, {"BYTES": 64},  128, 64,  "int4-baseline"),
]


def script(name: str, top: str, srcs: list[str], params: dict) -> str:
    log = f"{LOG_DIR}/{name}.txt".replace("\\", "/")
    # Yosys 0.69 (YoWASP) asserts in `hierarchy -chparam` with recursive sum_tree instances, so
    # parameters are set with `chparam -set` and the derived module is renamed back to a stable top name.
    chp = (" ".join(f"-set {k} {v}" for k, v in params.items()) + f" {top}") if params else ""
    L = [f"# EXP-0005 generic synthesis point '{name}': {top} {params}",
         "# Generated by analysis/hardware_gate/synth_points.py; run from the repository root.",
         f"tee -q -o {log} log ==== FlexTern generic synthesis: {name} ({top} {params}) ===="]
    L += [f"read_verilog -sv {s}" for s in srcs]
    L += ([f"chparam {chp}", "hierarchy -check -auto-top", f"rename -top {name}"] if params else [f"hierarchy -check -top {top}", f"rename -top {name}"])
    L += ["proc", "flatten", "opt_clean",
          f"tee -q -a {log} log ==== STAGE 1: coarse-grain cells (after proc/flatten/opt_clean) ====",
          "delete t:$scopeinfo", f"tee -q -a {log} stat",
          f"synth -top {name} -flatten",
          f"tee -q -a {log} log ==== STAGE 2: generic gate-level cells (after synth -flatten) ====",
          "delete t:$scopeinfo", f"tee -q -a {log} stat",
          f"tee -q -a {log} log ==== LTP: longest topological path, flip-flops excluded (generic gates, not timing) ====",
          f"tee -q -a {log} ltp -noff",
          "check -assert"]
    return "\n".join(L) + "\n"


def parse_log(path: str) -> dict:
    txt = open(path, encoding="utf-8", errors="replace").read()
    s1 = txt.split("==== STAGE 1")[1].split("==== STAGE 2")[0] if "==== STAGE 1" in txt else ""
    s2 = txt.split("==== STAGE 2")[1].split("==== LTP")[0] if "==== STAGE 2" in txt else ""
    def cells(block: str) -> dict:
        """Yosys 0.69 prints '<count> <cell>'; Yosys 0.52 prints '<cell> <count>'."""
        out = {}
        for m in re.finditer(r"^\s+(\d+)\s+(\$\S+)\s*$", block, re.M):
            out[m.group(2)] = out.get(m.group(2), 0) + int(m.group(1))
        for m in re.finditer(r"^\s+(\$\S+)\s+(\d+)\s*$", block, re.M):
            out[m.group(1)] = out.get(m.group(1), 0) + int(m.group(2))
        return out
    c1, c2 = cells(s1), cells(s2)
    tot = re.findall(r"^\s+(\d+)\s+cells\s*$", s2, re.M) or re.findall(r"Number of cells:\s+(\d+)", s2)
    ltp = re.search(r"Longest topological path[^\n]*\(length=(\d+)\)", txt) or re.search(r"Longest topological path[^\n]*?:\s*(\d+)", txt)
    dff = sum(v for k, v in c2.items() if k.startswith("$_DFF") or k.startswith("$_SDFF") or k.startswith("$_DFFE"))
    return {"coarse": c1, "gate": c2, "total_cells": int(tot[-1]) if tot else None,
            "mul_inferred": c1.get("$mul", 0), "dff_cells": dff, "ltp_gates": int(ltp.group(1)) if ltp else None}


def run_point(name: str, tool: str, timeout: int) -> tuple[float, int]:
    ys = os.path.join(SYNTH_DIR, f"{name}.ys").replace("\\", "/")
    t0 = time.time()
    if tool == "wsl":
        root = ROOT.replace("\\", "/")
        if re.match(r"^[A-Za-z]:/", root):
            root = "/mnt/" + root[0].lower() + root[2:]
        cmd = ["wsl", "-d", "Ubuntu", "--", "bash", "-lc", f"cd '{root}' && yosys -q {ys}"]
    else:
        exe = os.environ.get("FLEXTERN_YOSYS") or os.path.join(os.path.dirname(sys.executable), "Scripts", "yowasp-yosys.exe")
        cmd = [exe, "-q", ys]
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, timeout=timeout)
    return time.time() - t0, r.returncode


def tool_version(tool: str) -> str:
    if tool == "wsl":
        r = subprocess.run(["wsl", "-d", "Ubuntu", "--", "bash", "-lc", "yosys -V"], capture_output=True, text=True)
    else:
        exe = os.environ.get("FLEXTERN_YOSYS") or os.path.join(os.path.dirname(sys.executable), "Scripts", "yowasp-yosys.exe")
        r = subprocess.run([exe, "-V"], capture_output=True, text=True)
    return (r.stdout or r.stderr).strip().splitlines()[0]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tool", choices=["yowasp", "wsl"], default="yowasp")
    ap.add_argument("--points", default="all", help="comma-separated point names or 'all'")
    ap.add_argument("--timeout", type=int, default=5400)
    ap.add_argument("--generate-only", action="store_true")
    ap.add_argument("--parse-only", action="store_true")
    a = ap.parse_args()
    os.chdir(ROOT)
    os.makedirs(SYNTH_DIR, exist_ok=True); os.makedirs(LOG_DIR, exist_ok=True)
    sel = POINTS if a.points == "all" else [p for p in POINTS if p[0] in a.points.split(",")]
    for name, top, srcs, params, *_ in sel:
        with open(os.path.join(SYNTH_DIR, f"{name}.ys"), "w", encoding="utf-8", newline="\n") as f:
            f.write(script(name, top, srcs, params))
    if a.generate_only:
        print(f"{len(sel)} scripts written to {SYNTH_DIR}"); return 0
    meta_path = os.path.join(LOG_DIR, "runs.json")
    meta = json.load(open(meta_path, encoding="utf-8")) if os.path.isfile(meta_path) else {}
    if not a.parse_only:
        ver = tool_version(a.tool)
        for name, *_ in sel:
            print(f"[synth] {name} ({a.tool}) ...", flush=True)
            secs, rc = run_point(name, a.tool, a.timeout)
            meta[name] = {"tool": a.tool, "yosys": ver, "seconds": round(secs, 1), "returncode": rc}
            print(f"         {secs:.0f} s, rc={rc}", flush=True)
            json.dump(meta, open(meta_path, "w", encoding="utf-8"), indent=1)
    rows = []
    for name, top, srcs, params, terms, bytes_, kind in POINTS:
        log = os.path.join(LOG_DIR, f"{name}.txt")
        if not os.path.isfile(log):
            continue
        p = parse_log(log)
        m = meta.get(name, {})
        rows.append({"point": name, "kind": kind, "module": top, "params": json.dumps(params), "terms_per_cycle": terms,
                     "packed_bytes_per_cycle": bytes_, "total_generic_cells": p["total_cells"],
                     "mul_inferred": p["mul_inferred"], "dff_cells": p["dff_cells"],
                     "cells_excluding_dff": (p["total_cells"] - p["dff_cells"]) if p["total_cells"] is not None else None,
                     "cells_per_term": round(p["total_cells"] / terms, 2) if p["total_cells"] else None,
                     "ltp_gates_noff": p["ltp_gates"],
                     "coarse_add": p["coarse"].get("$add", 0), "coarse_sub": p["coarse"].get("$sub", 0),
                     "coarse_neg": p["coarse"].get("$neg", 0), "coarse_pmux": p["coarse"].get("$pmux", 0),
                     "coarse_eq": p["coarse"].get("$eq", 0), "coarse_mux": p["coarse"].get("$mux", 0),
                     "coarse_mul": p["coarse"].get("$mul", 0), "coarse_mem": p["coarse"].get("$mem_v2", 0) + p["coarse"].get("$mem", 0),
                     "gate_xor_xnor": p["gate"].get("$_XOR_", 0) + p["gate"].get("$_XNOR_", 0),
                     "gate_mux": p["gate"].get("$_MUX_", 0),
                     "tool": m.get("tool"), "yosys_version": m.get("yosys"), "seconds": m.get("seconds")})
    out = os.path.join("results", "hardware_gate", "synthesis.csv")
    with open(out, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys())); w.writeheader(); w.writerows(rows)
    print(f"{len(rows)} points -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
