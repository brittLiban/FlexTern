// =============================================================================
// y_dot16_tb.sv — testbench for Y-Dot16 v0.1
// =============================================================================
//
// Three independent test groups:
//
//   1. Deterministic cases, including the spec example and the boundary
//      cases that exercise the full 13-bit output range.
//   2. Randomized: N_RANDOM random 16-element vectors (default 10,000) with
//      weights drawn uniformly from {-1, 0, +1}; expected value computed in
//      the testbench with 32-bit integer math.
//   3. Python cross-check: vectors generated by scripts/gen_vectors.py using
//      reference/ternary_op.py, loaded with $readmemh. Each 176-bit line is
//      { 3'b0, expected[12:0], w_flat[31:0], x_flat[127:0] }. This confirms
//      two independently written implementations (Python and RTL) agree.
//      Path overridable with +vectors=<file>. If the file is missing the
//      loaded words are X and the comparison fails, so a missing file cannot
//      silently pass.
//
// Compile: iverilog -g2012 -o build/y_dot16_tb.vvp rtl/y_core.sv rtl/y_dot16.sv tests/y_dot16_tb.sv
// Run:     vvp build/y_dot16_tb.vvp
//
// Success line:  PASS: Y-Dot16 verification completed.
// =============================================================================

`timescale 1ns/1ps

module y_dot16_tb;

    localparam int N        = 16;
    localparam int N_RANDOM = 10000;
    localparam int N_XCHECK = 2000;

    logic [127:0]       x_flat;
    logic [31:0]        w_flat;
    logic signed [12:0] y;

    y_dot16 dut (.x_flat(x_flat), .w_flat(w_flat), .y(y));

    int errors = 0;
    int det_cases = 0, rand_cases = 0, xcheck_cases = 0;

    // Test-side copies of the current vector in integer form.
    int xs [0:N-1];
    int ws [0:N-1];

    function automatic logic [1:0] encode(input int w);
        case (w)
             0: encode = 2'b00;
             1: encode = 2'b01;
            -1: encode = 2'b11;
            default: $fatal(1, "encode(): invalid ternary weight %0d", w);
        endcase
    endfunction

    // Pack xs/ws into the flat DUT ports.
    task automatic drive();
        int i;
        begin
            x_flat = '0;
            w_flat = '0;
            for (i = 0; i < N; i++) begin
                x_flat[8*i +: 8] = xs[i][7:0];
                w_flat[2*i +: 2] = encode(ws[i]);
            end
            #1;
        end
    endtask

    function automatic int expected_dot();
        int i, s;
        begin
            s = 0;
            for (i = 0; i < N; i++) s = s + xs[i] * ws[i];
            expected_dot = s;
        end
    endfunction

    task automatic check(input string label);
        int exp, act;
        begin
            drive();
            exp = expected_dot();
            act = y;  // signed 13 -> int
            if (act !== exp) begin
                errors++;
                $display("MISMATCH [%s]: expected=%0d actual=%0d", label, exp, act);
                $display("   x = %0d %0d %0d %0d %0d %0d %0d %0d %0d %0d %0d %0d %0d %0d %0d %0d",
                    xs[0],xs[1],xs[2],xs[3],xs[4],xs[5],xs[6],xs[7],
                    xs[8],xs[9],xs[10],xs[11],xs[12],xs[13],xs[14],xs[15]);
                $display("   w = %0d %0d %0d %0d %0d %0d %0d %0d %0d %0d %0d %0d %0d %0d %0d %0d",
                    ws[0],ws[1],ws[2],ws[3],ws[4],ws[5],ws[6],ws[7],
                    ws[8],ws[9],ws[10],ws[11],ws[12],ws[13],ws[14],ws[15]);
            end
        end
    endtask

    task automatic fill(input int xv, input int wv);
        int i;
        for (i = 0; i < N; i++) begin xs[i] = xv; ws[i] = wv; end
    endtask

    // ---- Python cross-check storage ------------------------------------------
    logic [175:0] vec [0:N_XCHECK-1];
    string vec_path;

    initial begin
        int i, k;
        int exp, act;

        // ===== 1. Deterministic =================================================

        // Spec example extended to 16 elements: first four [5,8,3,7]·[+1,-1,0,+1] = 4,
        // remaining twelve are zero weight so the total is still 4.
        xs[0]=5; xs[1]=8; xs[2]=3; xs[3]=7;
        ws[0]=1; ws[1]=-1; ws[2]=0; ws[3]=1;
        for (i = 4; i < N; i++) begin xs[i] = 100; ws[i] = 0; end
        check("spec example [5,8,3,7]*[1,-1,0,1] = 4"); det_cases++;

        fill(127, 1);   check("all +127, w=+1 (expect +2032)");   det_cases++;
        fill(-128, 1);  check("all -128, w=+1 (expect -2048)");   det_cases++;
        fill(-128, -1); check("all -128, w=-1 (expect +2048)");   det_cases++;
        fill(127, -1);  check("all +127, w=-1 (expect -2032)");   det_cases++;
        fill(-128, 0);  check("all -128, w=0 (expect 0)");        det_cases++;
        fill(77, 0);    check("all zero weights (expect 0)");     det_cases++;

        // Alternating signs on activations with all +1 weights -> cancels to 0
        for (i = 0; i < N; i++) begin xs[i] = (i % 2 == 0) ? 100 : -100; ws[i] = 1; end
        check("alternating +/-100, w=+1 (expect 0)"); det_cases++;

        // Alternating weights on constant activations -> cancels to 0
        for (i = 0; i < N; i++) begin xs[i] = 55; ws[i] = (i % 2 == 0) ? 1 : -1; end
        check("x=55, alternating w (expect 0)"); det_cases++;

        // All three weight values present, mixed activations
        for (i = 0; i < N; i++) begin xs[i] = i * 8 - 64; ws[i] = (i % 3) - 1; end
        check("mixed weights -1/0/+1 pattern"); det_cases++;

        // Single non-zero term at each position carrying the worst case
        for (k = 0; k < N; k++) begin
            fill(0, 0);
            xs[k] = -128; ws[k] = -1;
            check($sformatf("lane %0d alone: -128*-1 (expect 128)", k)); det_cases++;
        end

        // ===== 2. Randomized ====================================================
        for (k = 0; k < N_RANDOM; k++) begin
            for (i = 0; i < N; i++) begin
                xs[i] = $signed($urandom_range(0, 255) - 128);   // -128..127
                ws[i] = $urandom_range(0, 2) - 1;                 // -1, 0, +1
            end
            check($sformatf("random #%0d", k));
            rand_cases++;
        end

        // ===== 3. Python cross-check via $readmemh ==============================
        if (!$value$plusargs("vectors=%s", vec_path))
            vec_path = "tests/vectors/y_dot16_vectors.hex";
        $readmemh(vec_path, vec);

        for (k = 0; k < N_XCHECK; k++) begin
            x_flat = vec[k][127:0];
            w_flat = vec[k][159:128];
            exp    = $signed(vec[k][172:160]);  // 13-bit two's complement
            #1;
            act = y;
            if (act !== exp || ^vec[k] === 1'bx) begin
                errors++;
                $display("MISMATCH [python xcheck #%0d]: expected=%0d actual=%0d (x=%h w=%h)",
                         k, exp, act, x_flat, w_flat);
            end
            xcheck_cases++;
        end

        // ===== Summary ==========================================================
        if (errors != 0) begin
            $display("FAIL: Y-Dot16 verification found %0d mismatch(es).", errors);
            $fatal(1, "Y-Dot16 verification failed");
        end else begin
            $display("%0d deterministic cases passed.", det_cases);
            $display("%0d randomized cases passed.", rand_cases);
            $display("%0d Python cross-check cases passed (%s).", xcheck_cases, vec_path);
            $display("PASS: Y-Dot16 verification completed.");
            $finish;
        end
    end

endmodule
